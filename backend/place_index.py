def find_place(text: str, region: str | None):
    if not region or region not in PLACES:
        return None
    low = text.lower()
    # Prefer longer names first so a shorter locality cannot shadow one inside it.
    for name, coords in sorted(PLACES[region].items(), key=lambda item: len(item[0]), reverse=True):
        if name.lower() in low:
            return {"place": name, "lat": coords[0], "lon": coords[1], "approximate": True}
    return None
